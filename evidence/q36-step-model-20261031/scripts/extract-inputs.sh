#!/usr/bin/env bash
# Writes inputs.wl (the Wolfram association q36in) from the sha256-pinned files of this directory.
# The hosted Wolfram evaluator cannot read local files, so every input is embedded as data; this script is the
# only path from the pinned files to that data and is rerun by the README check (byte-identical inputs.wl).
# No arithmetic happens here: integers and strings are copied, the README ladder medians are copied as text.
# usage (from the evidence directory): scripts/extract-inputs.sh > inputs.wl
set -eu
cd "$(dirname "$0")/.."
wl() { jq -c "$1" "$2" | tr '[]' '{}'; }   # JSON integer arrays -> Wolfram lists
readme=inputs/motor-chip-README.md
# lever-2 ladder table, README L247-250: | heads | lever 2 ms per stroke (median) | ...
ladder_line() { sed -n "${1}p" "$readme" | cut -d'|' -f3 | awk '{print $1}'; }
for l in 247 248 249 250; do
  sed -n "${l}p" "$readme" | grep -q '^| [1248] | [0-9.]* (' || { echo "README L$l is not a lever-2 ladder row" >&2; exit 1; }
done
stamp_median=$(sed -n 's/.*chip per stroke median \([0-9.]*\) ms.*/\1/p' inputs/stroke8l2-stamps.log)
echo '(* q36in: generated by scripts/extract-inputs.sh from the files pinned in SHA256SUMS; do not edit by hand *)'
echo 'q36in = <|'
echo "  \"source\" -> \"aien-sovereign-core-mv d3dec0eb evidence/motor-chip-20261021 + q36-host-20261020 goldens\","
for n in 1 2 4 8; do
  echo "  \"ladderNs$n\" -> $(wl '.stroke_chip_ns' inputs/stroke${n}l2-real.json),"
  echo "  \"ladderFileMedianNs$n\" -> $(jq '.stroke_chip_ns_median' inputs/stroke${n}l2-real.json),"
  echo "  \"ladderHeads$n\" -> $(jq '.heads' inputs/stroke${n}l2-real.json),"
done
echo "  \"readmeLadderMs\" -> {$(ladder_line 247), $(ladder_line 248), $(ladder_line 249), $(ladder_line 250)},"
echo "  \"stampsNs\" -> $(wl '.stroke_chip_ns' inputs/stroke8l2-stamps.json),"
echo "  \"stampsLogMedianMs\" -> $stamp_median,"
echo "  \"stampsKindNs\" -> <|$(jq -r '.timeline_last_stroke.per_kind | map("\"\(.kind)\" -> \(.ns)") | join(", ")' inputs/stroke8l2-stamps.json)|>,"
echo "  \"stampsKindLaunches\" -> <|$(jq -r '.timeline_last_stroke.per_kind | map("\"\(.kind)\" -> \(.launches)") | join(", ")' inputs/stroke8l2-stamps.json)|>,"
echo "  \"stampsTotalNs\" -> $(jq '.timeline_last_stroke.total_ns' inputs/stroke8l2-stamps.json),"
for f in 4p 4chat 8prompts 8prompts-b; do
  echo "  \"pinnedUnionMean[$f]\" -> $(jq '.mean_union' inputs/expert-union-$f.json),"
  echo "  \"pinnedUnionIndep[$f]\" -> $(jq '.independent_draws' inputs/expert-union-$f.json),"
done
for f in ladder1-p1 ladder2-p1p2 ladder4-p1234 4chat 8a ladder8-setb pair-code-p2 pair-code-review; do
  echo "  \"cells[$f]\" -> $(wl '.cells' derived/union-cells-$f.json),"
done
for k in expert gate_up down shared mix o_proj ab router lm_head layers routed_expert_tensor_sets_layer0; do
  echo "  \"bytes[$k]\" -> $(jq ".$k" derived/header-bytes.json),"
done
echo '  "end" -> True'
echo '|>;'
